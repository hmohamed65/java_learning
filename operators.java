public class operators {
    public static void main(String[] args) {
        int a=9;
        int b=90;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
        System.out.println(a>b ? "a is greater than b" : "b is greater than a");
        System.out.println(++a);
        System.out.println(--a);
    
        

    }
    
}
